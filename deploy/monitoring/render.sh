#!/usr/bin/env bash
# Renders the monitoring files that derive from the Helm chart, run from the repository root:
# - the Grafana dashboards in deploy/helm/opaa/dashboards/, built by build_dashboards.py with the
#   alert thresholds of the chart's values.yaml, for the chart's ConfigMaps and Compose alike;
# - the alert rules of the Compose monitoring (deploy/monitoring/prometheus/opaa-rules.yaml), the
#   chart's PrometheusRule for release "opaa" in namespace "opaa", whose labels the Compose
#   Prometheus attaches to its scrape of the backend.
# With --check it writes nothing and fails when a file differs; .github/workflows/helm-chart.yml
# runs it so. Needs helm, yq and python3.
set -euo pipefail

CHART_DIR="deploy/helm/opaa"
DASHBOARDS="$CHART_DIR/dashboards"
RULES="deploy/monitoring/prometheus/opaa-rules.yaml"
check=""
[ "${1:-}" = "--check" ] && check="--check"

work_dir="$(mktemp -d)"
trap 'rm -rf "$work_dir"' EXIT

yq -o json '.metrics' "$CHART_DIR/values.yaml" >"$work_dir/metrics.json"
python3 deploy/monitoring/build_dashboards.py --values "$work_dir/metrics.json" --out "$DASHBOARDS" $check

{
  echo "# Generated by deploy/monitoring/render.sh from the chart's PrometheusRule; edit the chart."
  helm template opaa "$CHART_DIR" --namespace opaa --values "$CHART_DIR/ci/minimal-values.yaml" \
    --set metrics.serviceMonitor.enabled=true --set metrics.prometheusRule.enabled=true \
    --show-only templates/prometheusrule.yaml | yq -e '.spec'
} >"$work_dir/opaa-rules.yaml"

if [ -n "$check" ]; then
  if ! diff -u "$RULES" "$work_dir/opaa-rules.yaml"; then
    echo "::error::$RULES is out of date. Run deploy/monitoring/render.sh." >&2
    exit 1
  fi
else
  cp "$work_dir/opaa-rules.yaml" "$RULES"
fi
